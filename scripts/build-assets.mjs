// Reads img/miolo.png, patches out the faint reference "@guisimara"
// watermark baked into it at y~1232-1254 (it visibly double-exposes with the
// dynamic CSS footer text rendered in the same spot — see DECISIONS.md #16),
// and writes lib/assets.generated.ts exporting the patched image (plus the
// capa mask and caption tag, used as-is) as base64 data URIs. Source files
// in img/ are left untouched; the patch is applied once here, same pattern
// as scripts/build-fonts.mjs.
//
// img/mascara.png (capa mask) is a custom-made gradient/vignette asset, not
// a stock photo — it never had the watermark baked in, so it's read as-is
// via plainDataUri(), not patched.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");

async function patchedDataUri(relativePath) {
  const filePath = path.join(root, relativePath);
  const cleanPatch = await sharp(filePath)
    .extract({ left: 0, top: 1180, width: 1080, height: 35 })
    .toBuffer();
  const buf = await sharp(filePath)
    .composite([{ input: cleanPatch, left: 0, top: 1225 }])
    .png()
    .toBuffer();
  return `data:image/png;base64,${buf.toString("base64")}`;
}

async function plainDataUri(relativePath) {
  const filePath = path.join(root, relativePath);
  const buf = await sharp(filePath).png().toBuffer();
  return `data:image/png;base64,${buf.toString("base64")}`;
}

const mioloBg = await patchedDataUri("img/miolo.png");
const capaMask = await plainDataUri("img/mascara.png");
const readCaptionTag = await plainDataUri("img/slug-legenda.png");

const out = `// AUTO-GENERATED by scripts/build-assets.mjs. Do not edit by hand.
export const MIOLO_BG_DATA_URI = ${JSON.stringify(mioloBg)};
export const CAPA_MASK_DATA_URI = ${JSON.stringify(capaMask)};
export const READ_CAPTION_TAG_DATA_URI = ${JSON.stringify(readCaptionTag)};
`;

writeFileSync(path.join(root, "lib", "assets.generated.ts"), out);
console.log("[build-assets] wrote lib/assets.generated.ts (%d bytes)", out.length);
