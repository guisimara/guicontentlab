// Reads @fontsource/poppins woff2 files (300 and 700, latin, normal) and
// writes lib/fonts.generated.ts exporting a CSS string with the fonts
// embedded as base64 data URIs. This guarantees the exact same font bytes
// are used for every render, with no dependency on system fonts.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const filesDir = path.join(root, "node_modules", "@fontsource", "poppins", "files");

const weightFile = (weight) => path.join(filesDir, `poppins-latin-${weight}-normal.woff2`);

function b64(weight) {
  const file = weightFile(weight);
  if (!existsSync(file)) {
    throw new Error(
      `Font file not found: ${file}. Did "npm install" run (@fontsource/poppins)?`
    );
  }
  return readFileSync(file).toString("base64");
}

const light = b64(300);
const bold = b64(700);

const css = `
@font-face {
  font-family: 'Poppins';
  font-style: normal;
  font-weight: 300;
  src: url(data:font/woff2;base64,${light}) format('woff2');
  font-display: block;
}
@font-face {
  font-family: 'Poppins';
  font-style: normal;
  font-weight: 700;
  src: url(data:font/woff2;base64,${bold}) format('woff2');
  font-display: block;
}
`.trim();

const out = `// AUTO-GENERATED by scripts/build-fonts.mjs. Do not edit by hand.
export const FONT_FACE_CSS = ${JSON.stringify(css)};
`;

writeFileSync(path.join(root, "lib", "fonts.generated.ts"), out);
console.log("[build-fonts] wrote lib/fonts.generated.ts (%d bytes)", out.length);
